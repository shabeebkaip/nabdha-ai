// Nabda AI — minimal i18n.
//
// ponytail: no i18n library. AR/EN + RTL for a 2-language marketing/app
// surface is a dictionary object + a `dir` attribute — a library (next-intl,
// react-i18next) earns its keep once we have plurals/dates/many namespaces,
// not before. Upgrade path: swap `t()` below for next-intl's `useTranslations`
// if the dictionary grows past a couple hundred keys or needs ICU plurals.
//
// Client-safe on purpose: no `next/headers` import here (see
// `src/lib/get-locale.ts` for the server-only cookie read) so this module
// can be imported from "use client" components like `language-switcher.tsx`
// and `pricing-plans.tsx`.

export const locales = ["en", "ar"] as const;
export type Locale = (typeof locales)[number];
export const defaultLocale: Locale = "en";
export const localeCookieName = "nabda_locale";

export function isLocale(value: string | undefined | null): value is Locale {
  return !!value && (locales as readonly string[]).includes(value);
}

export function dirFor(locale: Locale): "ltr" | "rtl" {
  return locale === "ar" ? "rtl" : "ltr";
}

