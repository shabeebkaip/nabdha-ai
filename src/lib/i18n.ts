export type DictKey = keyof (typeof dictionaries)["en"];

export function getDictionary(locale: Locale) {
  return dictionaries[locale];
}

export function t(locale: Locale, key: DictKey): string {
  return dictionaries[locale][key] ?? dictionaries[defaultLocale][key];
}

/** Same as `t`, with `{token}` substitution for the handful of strings that
 * need a runtime value (e.g. "Uses {n} credits"). ponytail: `{token}` string
 * replace, not a full ICU/format library — this dictionary has ~2 params
 * total, not worth a dependency. */
export function tf(locale: Locale, key: DictKey, vars: Record<string, string | number>): string {
  let out = t(locale, key);
  for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}
